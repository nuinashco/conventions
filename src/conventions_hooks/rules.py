"""`build-rules`: generate the guide and the plugin's skills and subagents from rules/.

Usage:

    build-rules            # rewrite every generated file that is stale

    build-rules --check    # change nothing; exit 1 naming the stale files

Run it at the root of nuinashco/conventions, whose dev group brings pyyaml; the hooks
that projects install never need it. It reads `rules/`, one file per area plus
`_intro.md`, `_decisions.md` and `_sources.md`, and the subagent sources in `agents/`.
It writes GUIDE.md, COVERAGE.md, the comment rules that `review-comments` ships with,
and the skills and subagents of the plugin in `plugins/conventions/`.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from collections.abc import Iterator, Sequence
from pathlib import Path

from attrs import frozen

RULES_DIR = Path("rules")
AGENTS_DIR = Path("agents")
PLUGIN_DIR = Path("plugins/conventions")
SKILLS_DIR = PLUGIN_DIR / "skills"
DOC_RULES = Path("src/conventions_hooks/doc_rules.md")
AGENTS = ("conventions-reviewer", "descriptions-judge")
HEADING = re.compile(
    r"^### (?P<id>[A-Z]+-\d+) (?P<level>MUST|SHOULD|MAY)(?: \[(?P<tag>[a-z]+)\])?$",
    re.MULTILINE,
)
STRAY_HEADING = re.compile(r"#{1,3}(?!#)")
FENCE = "```"
FRONTMATTER = re.compile(r"\A---\n(?P<meta>.*?)\n---\n", re.DOTALL)
CHECK = re.compile(r"\n\n\*Check:\* ")
WHY = "\n\n*Why:* "
SKILL_NAME = re.compile(r"[a-z][a-z0-9]*(-[a-z0-9]+)*")
PLACEHOLDER = re.compile(r"\{\{\s*([^{}]+?)\s*\}\}")
ABBREVIATIONS = frozenset({"e.g", "i.e", "vs", "ch", "cf", "etc"})
SUMMARY_WORDS = 20
SEPARATOR = " \u00b7 "
GENERATED = (
    "<!-- Generated by `make build` from {source}; edit that, not this file. -->"
)


class RulesError(Exception):
    """A file under `rules/` or `agents/` that does not have the documented shape."""


@frozen
class Rule:
    """One rule: its heading, body, optional *Why* and the *Check* that ends it."""

    id: str
    level: str
    tag: str
    body: str
    why: str
    check: str

    @property
    def label(self) -> str:
        """Return the level with the profile tag, such as `MUST [rnd]`."""
        return f"{self.level} [{self.tag}]" if self.tag else self.level

    @property
    def heading(self) -> str:
        return f"### {self.id} {self.label}"

    @property
    def anchor(self) -> str:
        return _slug(self.heading.removeprefix("### "))

    @property
    def text(self) -> str:
        """Return the rule as markdown, in the shape `rules/` writes it."""
        why = f"\n\n*Why:* {self.why}" if self.why else ""
        return f"{self.heading}\n\n{self.body}{why}\n\n*Check:* {self.check}"

    @property
    def review_only(self) -> bool:
        """Return whether every `;`-separated part of the *Check* is review."""
        return all(_reviewed(part) for part in self.check.split(";"))

    @property
    def review_in_part(self) -> bool:
        """Return whether a tool checks the rule but leaves part of it to review."""
        return not self.review_only and any(map(_reviewed, self.check.split(";")))

    @property
    def summary(self) -> str:
        """Return the opening sentences of the body, on one line.

        A first sentence under twenty words takes the next ones of its paragraph along,
        and a paragraph that ends in a colon takes the items of the list it leads in to.
        """
        lead, _, rest = self.body.partition("\n\n")
        sentences = _sentences(lead)
        summary = next(sentences)
        for sentence in sentences:
            if len(summary.split()) >= SUMMARY_WORDS:
                break
            summary = f"{summary} {sentence}"
        if not summary.endswith(":"):
            return summary
        if items := _items(rest.partition("\n\n")[0]):
            return f"{summary} {'; '.join(items)}."
        return f"{summary.removesuffix(':')}."


@frozen
class Area:
    """One `rules/<area>.md`: its skill's name and trigger, and its rules in order."""

    code: str
    title: str
    skill: str
    description: str
    paths: tuple[str, ...]
    intro: str
    rules: tuple[Rule, ...]
    source: str

    @classmethod
    def parse(cls, text: str, *, source: str) -> Area:
        """Return the area that the markdown `text` of `source` holds."""
        meta, body = _frontmatter(text, source=source)
        missing = {"area", "title", "skill", "description"} - set(meta)
        if missing:
            raise RulesError(
                f"{source}: frontmatter lacks {', '.join(sorted(missing))}"
            )
        code, skill = str(meta["area"]), str(meta["skill"])
        if not SKILL_NAME.fullmatch(skill):
            raise RulesError(f"{source}: skill {skill!r} is not kebab-case")
        paths = meta.get("paths", [])
        if not isinstance(paths, list) or not all(isinstance(p, str) for p in paths):
            raise RulesError(f"{source}: paths must be a list of globs")
        if stray := _stray_heading(body):
            raise RulesError(
                f"{source}: {stray!r} is not a `### <ID> <LEVEL>` rule heading"
            )
        headings = list(HEADING.finditer(body))
        if not headings:
            raise RulesError(f"{source}: no `### <ID> <LEVEL>` rule headings")
        ends = [m.start() for m in headings[1:]] + [len(body)]
        rules = tuple(
            _rule(m, body[m.end() : end], source=source)
            for m, end in zip(headings, ends, strict=True)
        )
        if wrong := [r.id for r in rules if not r.id.startswith(f"{code}-")]:
            raise RulesError(f"{source}: {', '.join(wrong)} do not belong to {code}")
        return cls(
            code=code,
            title=str(meta["title"]),
            skill=skill,
            description=" ".join(str(meta["description"]).split()),
            paths=tuple(paths),
            intro=body[: headings[0].start()].strip(),
            rules=rules,
            source=source,
        )

    @property
    def name(self) -> str:
        return f"{self.title} ({self.code})"


@frozen
class Page:
    """A file of `rules/` that is not an area: a title over markdown."""

    title: str
    body: str

    @classmethod
    def load(cls, path: Path) -> Page:
        if not path.is_file():
            raise RulesError(f"{path}: missing; every guide has it")
        meta, body = _frontmatter(path.read_text(encoding="utf-8"), source=str(path))
        if "title" not in meta:
            raise RulesError(f"{path}: frontmatter lacks title")
        return cls(title=str(meta["title"]), body=body.strip())


@frozen
class Guide:
    """Everything `rules/` holds: the intro, the areas in order, decisions, sources."""

    title: str
    intro: str
    areas: tuple[Area, ...]
    decisions: Page
    sources: Page

    @classmethod
    def load(cls, directory: Path) -> Guide:
        """Return the guide in `directory`, checking its shape and its rule IDs."""
        intro = directory / "_intro.md"
        if not intro.is_file():
            raise RulesError(f"{intro}: missing; run build-rules at the repo root")
        meta, body = _frontmatter(intro.read_text(encoding="utf-8"), source=str(intro))
        found: dict[str, Area] = {}
        for path in sorted(directory.glob("[!_]*.md")):
            source = str(path.relative_to(directory.parent))
            area = Area.parse(path.read_text(encoding="utf-8"), source=source)
            if area.code in found:
                raise RulesError(
                    f"{path}: area {area.code} is also {found[area.code].source}"
                )
            found[area.code] = area
        order = [str(code) for code in _list(meta, "areas", source=str(intro))]
        if sorted(order) != sorted(found):
            raise RulesError(
                f"{intro}: areas lists {', '.join(order)}; "
                f"the area files are {', '.join(sorted(found))}"
            )
        guide = cls(
            title=str(meta.get("title", "")),
            intro=body.strip(),
            areas=tuple(found[code] for code in order),
            decisions=Page.load(directory / "_decisions.md"),
            sources=Page.load(directory / "_sources.md"),
        )
        retired = _list(meta, "retired", source=str(intro))
        guide.validate(retired=frozenset(map(str, retired)))
        return guide

    def validate(self, *, retired: frozenset[str]) -> None:
        """Raise a `RulesError` for a repeated or retired rule ID or skill name."""
        ids = [rule.id for rule in self.rules()]
        if repeated := sorted({i for i in ids if ids.count(i) > 1}):
            raise RulesError(f"rule IDs used twice: {', '.join(repeated)}")
        if reused := sorted(set(ids) & retired):
            raise RulesError(
                f"retired rule IDs reused: {', '.join(reused)}; pick new IDs"
            )
        skills = [area.skill for area in self.areas]
        if len(set(skills)) < len(skills):
            raise RulesError(f"skill names used twice: {', '.join(skills)}")

    def rules(self) -> Iterator[Rule]:
        for area in self.areas:
            yield from area.rules

    def rule(self, rule_id: str) -> Rule:
        """Return the rule `rule_id`."""
        for rule in self.rules():
            if rule.id == rule_id:
                return rule
        raise RulesError(f"no rule {rule_id} under rules/")

    def area(self, code: str) -> Area:
        """Return the area `code`."""
        for area in self.areas:
            if area.code == code:
                return area
        raise RulesError(f"no area {code} under rules/")


def outputs(root: Path) -> dict[Path, str]:
    """Return each generated file, relative to `root`, with the text it should have."""
    guide = Guide.load(root / RULES_DIR)
    files = {
        Path("GUIDE.md"): guide_page(guide),
        Path("COVERAGE.md"): coverage_page(guide),
        DOC_RULES: doc_rules_page(guide),
    }
    for area in guide.areas:
        files[SKILLS_DIR / area.skill / "SKILL.md"] = skill_page(area)
    for name in AGENTS:
        source = AGENTS_DIR / f"{name}.md"
        if not (root / source).is_file():
            raise RulesError(f"{source}: missing; it is the source of the {name} agent")
        text = (root / source).read_text(encoding="utf-8")
        files[PLUGIN_DIR / "agents" / f"{name}.md"] = agent_page(
            text, guide, source=str(source)
        )
    return files


def stale(root: Path) -> list[Path]:
    """Return the generated files under `root` that differ from what `rules/` says.

    A skill that no area generates any more is stale too: `write` deletes it.
    """
    return _stale(root, outputs(root))


def write(root: Path) -> tuple[list[Path], list[Path]]:
    """Bring the generated files under `root` up to date.

    Returns:
        The paths it rewrote, and the paths of the orphan skills it deleted.
    """
    expected = outputs(root)
    written, removed = [], []
    for path in _stale(root, expected):
        target = root / path
        if path in expected:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected[path], encoding="utf-8")
            written.append(path)
        else:
            target.unlink()
            if not any(target.parent.iterdir()):
                target.parent.rmdir()
            removed.append(path)
    return written, removed


def guide_page(guide: Guide) -> str:
    """Return GUIDE.md: intro, quick reference, areas in order, decisions, sources."""
    lead, _, rest = guide.intro.partition("\n## ")
    rest = f"## {rest}" if rest else ""
    numbered = [f"{n}. {area.name}" for n, area in enumerate(guide.areas, start=1)]
    contents = [
        _links(
            [*re.findall(r"^## (.+)$", guide.intro, re.MULTILINE), "Quick reference"]
        ),
        SEPARATOR.join(
            f"[{area.title}](#{_slug(heading)})"
            for area, heading in zip(guide.areas, numbered, strict=True)
        ),
        _links([guide.decisions.title, guide.sources.title]),
    ]
    rows = [
        f"| [{r.id}](#{r.anchor}) | {r.label} | {_cell(r.summary)} |"
        for r in guide.rules()
    ]
    parts = [
        GENERATED.format(source="rules/"),
        f"# {guide.title}",
        lead.strip(),
        "\n".join(f"- {line}" for line in contents),
        rest,
        "## Quick reference\n\n| rule | level | summary |\n|---|---|---|\n"
        + "\n".join(rows),
    ]
    for area, heading in zip(guide.areas, numbered, strict=True):
        parts += [f"## {heading}", area.intro, *(rule.text for rule in area.rules)]
    parts += [f"## {guide.decisions.title}", guide.decisions.body]
    parts += [f"## {guide.sources.title}", guide.sources.body]
    return _join(parts)


def coverage_page(guide: Guide) -> str:
    """Return COVERAGE.md: the MUST rules that only review checks, by area."""
    musts = [rule for rule in guide.rules() if rule.level == "MUST"]
    backlog = [rule for rule in musts if rule.review_only]
    parts = [
        GENERATED.format(source="rules/"),
        "# Coverage",
        f"MUST rules whose only *Check* is review: {len(backlog)} of {len(musts)}. "
        "Each is a candidate for a hook or a test (TOOL-1). When a tool takes one "
        "over, name it in the rule's *Check* under `rules/`, run `make build`, and "
        "the rule leaves this list.",
    ]
    for area in guide.areas:
        if found := [r for r in area.rules if r.level == "MUST" and r.review_only]:
            parts.append(f"## {area.name}: {len(found)}")
            parts.append(
                "\n".join(
                    f"- [{r.id}](GUIDE.md#{r.anchor}): {r.summary}" for r in found
                )
            )
    return _join(parts)


def doc_rules_page(guide: Guide) -> str:
    """Return the comment and docstring rules that `review-comments` hands its judge."""
    area = guide.area("DOC")
    return _join(
        [
            GENERATED.format(source=area.source),
            f"# {area.name}",
            area.intro,
            *(rule.text for rule in area.rules),
        ]
    )


def skill_page(area: Area) -> str:
    """Return the SKILL.md of `area`: review-only rules in full, the rest in brief."""
    meta: dict[str, object] = {"name": area.skill, "description": area.description}
    if area.paths:
        meta["paths"] = list(area.paths)
    judged = [rule for rule in area.rules if rule.review_only]
    tooled = [rule for rule in area.rules if not rule.review_only]
    if judged and tooled:
        purpose = (
            "first the ones only judgement checks, in full, then the ones a tool checks"
        )
    elif judged:
        purpose = "no tool checks them, so apply each with judgement"
    else:
        purpose = "a tool checks every one; follow them as you write"
    parts = [
        _dump_frontmatter(meta) + GENERATED.format(source=area.source),
        f"# {area.name}",
        f"The {area.title.lower()} rules of nuinashco/conventions: {purpose}.",
        area.intro,
    ]
    if judged:
        parts += ["## Apply with judgement", *(rule.text for rule in judged)]
    if tooled:
        parts += [
            "## Checked by tools",
            "Linters, hooks and the template report these; follow them as you write.",
            "\n".join(
                f"- **{r.id}** {r.label}: {r.summary} *Check:* {_line(r.check)}"
                for r in tooled
            ),
        ]
    return _join(parts)


def agent_page(text: str, guide: Guide, *, source: str) -> str:
    """Return a subagent from its source, with every placeholder filled in.

    `{{checklist}}` becomes the review-only rules by area, then the rules a tool checks
    only in part; `{{rule:DOC-7}}` becomes that rule in full.
    """
    import yaml

    match = FRONTMATTER.match(text)
    if not match or "name" not in (yaml.safe_load(match["meta"]) or {}):
        raise RulesError(f"{source}: starts without frontmatter naming the agent")

    def fill(placeholder: re.Match[str]) -> str:
        name = placeholder[1]
        if name == "checklist":
            return checklist(guide)
        if name.startswith("rule:"):
            return guide.rule(name.removeprefix("rule:")).text
        raise RulesError(
            f"{source}: unknown placeholder {name!r}; use checklist or rule:<ID>"
        )

    body = PLACEHOLDER.sub(fill, text[match.end() :])
    generated = GENERATED.format(source=f"{source} and rules/")
    return f"{text[: match.end()]}\n{generated}\n{body}"


def checklist(guide: Guide) -> str:
    """Return the review-only rules by area in brief, then the partly checked ones.

    Rules of the second kind come in full: what a tool leaves to judgement is often
    beyond what a summary holds.
    """
    lines = []
    for area in guide.areas:
        if judged := [rule for rule in area.rules if rule.review_only]:
            lines.append(f"- {area.name}:")
            lines += [f"  - **{r.id}** {r.label}: {r.summary}" for r in judged]
    parts = ["\n".join(lines)]
    if partly := [rule for rule in guide.rules() if rule.review_in_part]:
        parts.append("Tools check these only in part; judge what they leave:")
        parts += [rule.text for rule in partly]
    return "\n\n".join(part for part in parts if part)


def main(argv: Sequence[str] | None = None) -> int:
    """Regenerate the files `rules/` and `agents/` describe, or check they are fresh."""
    args = sys.argv[1:] if argv is None else list(argv)
    if args not in ([], ["--check"]):
        print(__doc__)
        return 0 if args in (["-h"], ["--help"]) else 2
    if importlib.util.find_spec("yaml") is None:
        print(
            "error: pyyaml is not installed; run `uv run build-rules` at the root of "
            "nuinashco/conventions, whose dev group has it",
            file=sys.stderr,
        )
        return 2
    root = Path.cwd()
    try:
        if args == ["--check"]:
            found = stale(root)
            for path in found:
                print(f"{path}: stale; run `make build`")
            return 1 if found else 0
        written, removed = write(root)
        for path in written:
            print(f"wrote {path}")
        for path in removed:
            print(f"removed {path}")
    except RulesError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    return 0


def _rule(heading: re.Match[str], section: str, *, source: str) -> Rule:
    content = f"\n\n{section.strip()}"
    checks = list(CHECK.finditer(content))
    if len(checks) > 1:
        raise RulesError(
            f"{source}: {heading['id']} has more than one *Check:* paragraph; "
            "is the heading after it malformed?"
        )
    check = content[checks[-1].end() :] if checks else ""
    if not check or "\n\n" in check:
        raise RulesError(
            f"{source}: {heading['id']} must end with one `*Check:* ...` paragraph"
        )
    head = content[: checks[-1].start()]
    body, sep, why = head.rpartition(WHY)
    if not sep or "\n\n" in why:
        body, why = head, ""
    body = body.strip()
    if not body or "\n\n*Why:*" in f"\n\n{body}":
        raise RulesError(
            f"{source}: {heading['id']} needs a body, then *Why:* right before *Check:*"
        )
    return Rule(
        id=heading["id"],
        level=heading["level"],
        tag=heading["tag"] or "",
        body=body,
        why=why,
        check=check,
    )


def _stray_heading(body: str) -> str:
    """Return the first heading outside a code fence that is not a rule heading."""
    fenced = False
    for line in body.splitlines():
        if line.lstrip().startswith(FENCE):
            fenced = not fenced
        elif not fenced and STRAY_HEADING.match(line) and not HEADING.fullmatch(line):
            return line
    return ""


def _frontmatter(text: str, *, source: str) -> tuple[dict[str, object], str]:
    import yaml

    match = FRONTMATTER.match(text)
    if not match:
        raise RulesError(f"{source}: starts without `---` frontmatter")
    meta = yaml.safe_load(match["meta"]) or {}
    if not isinstance(meta, dict):
        raise RulesError(f"{source}: frontmatter is not a mapping")
    return {str(key): value for key, value in meta.items()}, text[match.end() :]


def _dump_frontmatter(meta: dict[str, object]) -> str:
    import yaml

    dumped = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=10_000)
    return f"---\n{dumped}---\n\n"


def _list(meta: dict[str, object], key: str, *, source: str) -> list[object]:
    value = meta.get(key, [])
    if not isinstance(value, list):
        raise RulesError(f"{source}: {key} must be a list")
    return value


def _stale(root: Path, expected: dict[Path, str]) -> list[Path]:
    changed = [
        path
        for path, text in expected.items()
        if not (root / path).is_file()
        or (root / path).read_text(encoding="utf-8") != text
    ]
    skills = (root / SKILLS_DIR).glob("*/SKILL.md")
    orphans = [
        p.relative_to(root) for p in skills if p.relative_to(root) not in expected
    ]
    return sorted(changed + orphans)


def _reviewed(part: str) -> bool:
    return part.strip().lower().startswith("review")


def _sentences(paragraph: str) -> Iterator[str]:
    """Yield the sentences of a markdown paragraph, ignoring code, links and asides."""
    text = " ".join(paragraph.split())
    code, depth, start = False, 0, 0
    for index, char in enumerate(text):
        if char == "`":
            code = not code
        elif code:
            continue
        elif char in "([":
            depth += 1
        elif char in ")]":
            depth = max(depth - 1, 0)
        elif depth == 0 and _ends_sentence(text, index=index, start=start):
            yield text[start : index + 1]
            start = index + 2
    if text[start:]:
        yield text[start:]


def _items(paragraph: str) -> list[str]:
    """Return the items of a markdown list, each on one line without its end mark."""
    items: list[str] = []
    for line in paragraph.splitlines():
        if line.startswith("- "):
            items.append(line.removeprefix("- ").strip())
        elif items and line.strip():
            items[-1] = f"{items[-1]} {line.strip()}"
        else:
            return []
    return [item.removesuffix(";").removesuffix(".") for item in items]


def _ends_sentence(text: str, *, index: int, start: int) -> bool:
    words = text[start:index].split()
    return (
        text[index] in ".!?"
        and text[index + 1 : index + 2] == " "
        and bool(words)
        and words[-1] not in ABBREVIATIONS
    )


def _slug(heading: str) -> str:
    """Return the anchor GitHub gives `heading`."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def _links(titles: list[str]) -> str:
    return SEPARATOR.join(f"[{title}](#{_slug(title)})" for title in titles)


def _line(text: str) -> str:
    return " ".join(text.split())


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _join(parts: list[str]) -> str:
    return "\n\n".join(part.strip("\n") for part in parts if part.strip()) + "\n"
