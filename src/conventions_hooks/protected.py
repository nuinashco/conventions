"""`check-protected`: what `.gitattributes` marks is not edited by hand (GUIDE TOOL-5).

Usage:

    check-protected vendor/lib/core.py configs/run.yaml   # says which are protected

    check-protected --claude-hook    # Claude Code PreToolUse hook: reads its JSON

A `.gitattributes` line such as `vendor/** protected=vendored` marks the files; the
value picks the reason shown, and a path that reaches a marked file through a symlink
is protected like the file. A file whose leading comment lines include one starting
with `# Generated by` is protected as generated wherever it lives, since generated
config files share their folders with hand-written presets; a byte order mark, blank
lines and a `---` line may come before those comments. In hook mode an edit to a
marked file is denied through Claude Code's JSON output, which hands the reason to
Claude. The nearest `pyproject.toml` above the file that has a `[tool.conventions]`
table opts the repo in, so vendored code that brings its own `pyproject.toml` stays
protected; a file with no such table above it is left alone. The exit code stays 0, so
a broken environment never blocks every edit. A repo whose `ignore` lists TOOL-5
protects nothing. Commands such as `make configs` or `copier update` still rewrite
these files.

A file inside a nested git repository (a submodule or another checkout) follows that
repository's .gitattributes.
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections.abc import Sequence
from itertools import dropwhile
from pathlib import Path

from conventions_hooks.settings import Settings, SettingsError

RULE = "TOOL-5"
REASONS = {
    "generated": (
        "it is generated; change its source and regenerate it (its header says how)"
    ),
    "vendored": (
        "it is vendored from another repo; change it there and copy it in again"
    ),
    "published": (
        "it is a third-party file kept as published; copy it elsewhere to change it"
    ),
}
UNMARKED = ("unspecified", "unset")
GENERATED_HEADER = "# Generated by"


def main(argv: Sequence[str] | None = None) -> int:
    """Report the protected paths named on the command line, or refuse a Claude edit."""
    args = sys.argv[1:] if argv is None else list(argv)
    if args == ["--claude-hook"]:
        return claude_hook(sys.stdin.read())
    if not args or any(arg.startswith("-") for arg in args):
        print(__doc__)
        return 0 if args in (["-h"], ["--help"]) else 2
    found = []
    for arg in args:
        path = Path(arg).absolute()
        try:
            checked = _settings(path).keeps(RULE)
        except SettingsError as e:
            print(f"error: {e}", file=sys.stderr)
            return 2
        if checked and (why := reason(path)):
            found.append((arg, why))
    for arg, why in found:
        print(f"{arg}: {why}")
    return 1 if found else 0


def claude_hook(payload: str) -> int:
    """Deny a Claude Code edit to a protected file, with the reason."""
    data = json.loads(payload)
    tool_input = data.get("tool_input") or {}
    raw = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not raw:
        return 0
    path = Path(data.get("cwd") or ".") / raw
    try:
        settings = _settings(path)
    except SettingsError:
        return 0
    if not (settings.enabled and settings.keeps(RULE)):
        return 0
    why = reason(path)
    if why is None:
        return 0
    decision = {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": f"{raw} must not be edited by hand; {why}",
    }
    print(json.dumps({"hookSpecificOutput": decision}))
    return 0


def reason(path: Path) -> str | None:
    """Return why `path` must not be edited by hand, or None when it may be.

    Git is asked about the path as written and about the file it resolves to, so a
    protected file reached through a symlink is refused too.
    """
    for asked in dict.fromkeys((path, _resolved(path))):
        if value := _attribute(asked):
            return REASONS.get(value, "it is marked protected in .gitattributes")
    return _by_header(path)


def _attribute(path: Path) -> str | None:
    """Return the value git gives the `protected` attribute of `path`, if it has one."""
    # The nearest existing directory finds the repo, even for a file not written yet.
    cwd = next((p for p in path.parents if p.is_dir()), Path.cwd())
    try:
        result = subprocess.run(
            ["git", "check-attr", "protected", "--", str(path)],
            cwd=cwd,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:  # `git` is not installed.
        return None
    value = result.stdout.strip().rpartition(": ")[2]
    if result.returncode != 0 or not value or value in UNMARKED:
        return None
    return value


def _settings(path: Path) -> Settings:
    """Return the settings of the nearest pyproject.toml above `path` that opts in.

    A pyproject.toml without the table is passed by, since vendored code is copied in
    with its own; with no table above `path` the settings are not enabled.

    Raises:
        SettingsError: a pyproject.toml on the way is not TOML, or its table is
            malformed.
    """
    for directory in path.absolute().parents:
        pyproject = directory / "pyproject.toml"
        if pyproject.is_file() and (settings := Settings.parse(pyproject)).enabled:
            return settings
    return Settings(enabled=False)


def _resolved(path: Path) -> Path:
    try:
        return path.resolve()
    except RuntimeError:  # Python 3.12 raises it for a symlink loop.
        return path


def _by_header(path: Path) -> str | None:
    try:
        # `utf-8-sig` reads past the byte order mark that some editors write first.
        with path.open(encoding="utf-8-sig") as file:
            for line in dropwhile(lambda first: first.strip() in ("", "---"), file):
                if not line.startswith("#"):
                    return None
                if line.startswith(GENERATED_HEADER):
                    return REASONS["generated"]
    except (OSError, UnicodeDecodeError):  # Missing, a directory, or binary.
        return None
    return None
