"""Files marked `protected` in .gitattributes are refused, with the reason."""

from __future__ import annotations

import json
import subprocess

import pytest

from conventions_hooks.protected import claude_hook, main, reason


@pytest.fixture
def repo(opted_in):
    subprocess.run(["git", "init", "-q"], cwd=opted_in, check=True)
    (opted_in / ".gitattributes").write_text(
        "vendor/** linguist-vendored protected=vendored\n"
        "configs/defaults/** linguist-generated protected=generated\n"
        "notes/** protected\n",
        encoding="utf-8",
    )
    return opted_in


@pytest.mark.parametrize(
    ("path", "expected"),
    [
        ("vendor/lib/core.py", "vendored from another repo"),
        ("configs/defaults/new/run.yaml", "generated"),
        ("notes/todo.md", "marked protected"),
        ("src/pkg/config.py", None),
    ],
    ids=["vendored", "generated-not-written-yet", "bare-attribute", "unmarked"],
)
def test_reason_follows_the_gitattributes_value(repo, path, expected):
    why = reason(repo / path)

    assert why is None if expected is None else expected in why


def test_generated_header_protects_a_file_no_attribute_marks(repo):
    (repo / "configs" / "shape").mkdir(parents=True)
    (repo / "configs" / "shape" / "square.yaml").write_text(
        "# Generated by `make configs` from SquareConfig; edit the schema.\n"
    )
    (repo / "configs" / "shape" / "big.yaml").write_text("defaults:\n  - square\n")

    assert "generated" in (reason(repo / "configs/shape/square.yaml") or "")
    assert reason(repo / "configs/shape/big.yaml") is None


def test_generated_header_after_a_package_line_still_protects(repo):
    (repo / "configs" / "metric").mkdir(parents=True)
    (repo / "configs" / "metric" / "mae.yaml").write_text(
        "# @package metric.mae\n# Generated by `make configs` from MAEConfig.\n"
    )
    (repo / "configs" / "metric" / "note.yaml").write_text(
        "kind: mae\n# Generated by hand, not by make configs.\n"
    )

    assert "generated" in (reason(repo / "configs/metric/mae.yaml") or "")
    assert reason(repo / "configs/metric/note.yaml") is None


def test_path_outside_any_repo_is_not_protected(tmp_path):
    assert reason(tmp_path / "loose.py") is None


def test_claude_edit_to_protected_file_is_denied_with_reason(repo, capsys):
    payload = {"cwd": str(repo), "tool_input": {"file_path": "vendor/lib/core.py"}}

    assert claude_hook(json.dumps(payload)) == 0
    decision = json.loads(capsys.readouterr().out)["hookSpecificOutput"]
    assert decision["permissionDecision"] == "deny"
    assert "change it there" in decision["permissionDecisionReason"]


@pytest.mark.parametrize(
    "pyproject",
    ['[project]\nname = "x"\n', '[tool.conventions]\nignore = ["TOOL-5"]\n'],
    ids=["not-opted-in", "ignores-tool-5"],
)
def test_claude_edit_is_allowed_where_the_repo_does_not_protect(
    repo, capsys, pyproject
):
    (repo / "pyproject.toml").write_text(pyproject)
    payload = {"cwd": str(repo), "tool_input": {"file_path": "vendor/lib/core.py"}}

    assert claude_hook(json.dumps(payload)) == 0
    assert capsys.readouterr().out == ""


def test_command_line_lists_only_protected_paths(repo, capsys, monkeypatch):
    monkeypatch.chdir(repo)

    assert main(["vendor/lib/core.py", "src/pkg/config.py"]) == 1
    assert capsys.readouterr().out.splitlines() == [
        "vendor/lib/core.py: it is vendored from another repo; change it there and "
        "copy it in again"
    ]


def test_command_line_protects_nothing_in_a_repo_that_ignores_tool_5(
    repo, capsys, monkeypatch
):
    (repo / "pyproject.toml").write_text('[tool.conventions]\nignore = ["TOOL-5"]\n')
    monkeypatch.chdir(repo)

    assert main(["vendor/lib/core.py"]) == 0
    assert capsys.readouterr().out == ""
